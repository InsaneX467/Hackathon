export function findLocationById(id) {
  if (!id) return MONITORED_LOCATIONS[0];
  const exact = MONITORED_LOCATIONS.find(loc => loc.id === id);
  if (exact) return exact;

  // Search by district or name substring
  const cleanId = id.toLowerCase().replace(/[-_]/g, ' ');
  const partial = MONITORED_LOCATIONS.find(loc => 
    cleanId.includes(loc.name.toLowerCase()) ||
    cleanId.includes(loc.district.toLowerCase()) ||
    loc.id.includes(id)
  );
  return partial || MONITORED_LOCATIONS[0];
}

export function searchLocations(query) {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();
  return MONITORED_LOCATIONS.filter(loc => 
    loc.name.toLowerCase().includes(q) ||
    loc.district.toLowerCase().includes(q) ||
    loc.state.toLowerCase().includes(q)
  );
}
